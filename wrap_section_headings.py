"""Wrap ALL CAPS Greek section headings in \\sectionheading{} macro."""


def wrap_headings(latex):
    """Wrap ALL CAPS Greek section headings in \\sectionheading{}.

    Operates on already-processed text (after process_latex transformations).
    Each replacement is expected to match exactly once; a warning is printed
    if the count differs.
    """
    for old, new, desc in REPLACEMENTS:
        count = latex.count(old)
        if count != 1:
            print(f"WARNING: '{desc}' matched {count} times (expected 1)")
            continue
        latex = latex.replace(old, new, 1)
    return latex


